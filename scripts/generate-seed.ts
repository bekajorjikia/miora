/**
 * Rebuild src/lib/seed-data.ts from a Supabase export, so the offline fallback
 * mirrors what the admin panel holds.
 *
 *   npx tsx scripts/generate-seed.ts path/to/export.json
 *
 * The export is the result of this query in the Supabase SQL editor:
 *
 *   select json_build_object(
 *     'restaurant', (select to_json(r) from (select * from restaurants where id = 'miora') r),
 *     'categories', (select json_agg(c order by c.sort_order) from (select id, name, sort_order from categories where restaurant_id = 'miora') c),
 *     'items', (select json_agg(i order by i.sort_order) from (select id, category_id, name, description, tags, price_minor, photo_url, available, sort_order from menu_items where restaurant_id = 'miora') i)
 *   ) as menu;
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

interface ExportedRestaurant {
  id: string;
  name: string;
  default_language: string;
  supported_languages: string[];
  currency: string;
}

interface ExportedCategory {
  id: string;
  name: Record<string, string>;
  sort_order: number;
}

interface ExportedItem {
  id: string;
  category_id: string;
  name: Record<string, string>;
  description: Record<string, string> | null;
  tags: string[] | null;
  price_minor: number | null;
  photo_url: string | null;
  available: boolean;
  sort_order: number;
}

interface MenuExport {
  restaurant: ExportedRestaurant;
  categories: ExportedCategory[];
  items: ExportedItem[];
}

const exportPath = process.argv[2];
if (!exportPath) {
  throw new Error("Usage: npx tsx scripts/generate-seed.ts <export.json>");
}

const data = JSON.parse(readFileSync(exportPath, "utf8")) as MenuExport;

function literal(value: unknown): string {
  return JSON.stringify(value);
}

function localized(value: Record<string, string> | null): string {
  const en = value?.en ?? "";
  const ka = value?.ka ?? "";
  return `{ en: ${literal(en)}, ka: ${literal(ka)} }`;
}

/** Categories keep the admin's order but get gap-free sortOrder values. */
const categories = [...data.categories].sort((a, b) => a.sort_order - b.sort_order);

const categoryLines = categories.map(
  (category, index) =>
    `  {\n` +
    `    id: ${literal(category.id)},\n` +
    `    restaurantId,\n` +
    `    name: ${localized(category.name)},\n` +
    `    sortOrder: ${index + 1},\n` +
    `  },`,
);

const items = [...data.items].sort((a, b) => {
  const categoryDelta =
    categories.findIndex((category) => category.id === a.category_id) -
    categories.findIndex((category) => category.id === b.category_id);
  if (categoryDelta !== 0) {
    return categoryDelta;
  }
  if (a.sort_order !== b.sort_order) {
    return a.sort_order - b.sort_order;
  }
  return a.id.localeCompare(b.id);
});

const itemLines = items.map((item) => {
  const lines = [
    `    id: ${literal(item.id)},`,
    `    restaurantId,`,
    `    categoryId: ${literal(item.category_id)},`,
    `    name: ${localized(item.name)},`,
    `    description: ${localized(item.description)},`,
    `    tags: ${literal(item.tags ?? [])} as Tag[],`,
    `    available: ${item.available},`,
    `    sortOrder: ${item.sort_order},`,
  ];
  if (item.price_minor !== null) {
    lines.push(`    priceMinor: ${item.price_minor},`);
  }
  if (item.photo_url) {
    lines.push(`    photoUrl: ${literal(item.photo_url)},`);
  }
  return `  {\n${lines.join("\n")}\n  },`;
});

const unknownCategory = items.find(
  (item) => !categories.some((category) => category.id === item.category_id),
);
if (unknownCategory) {
  throw new Error(`Item ${unknownCategory.id} points at a missing category.`);
}

const file = `// Generated by scripts/generate-seed.ts from a Supabase export — do not edit by hand.
// This is the offline mirror of the live menu, used when ALLOW_SEED_FALLBACK is on
// and in development.
import type { Category, MenuItem, Restaurant, Tag } from "@/lib/types";

export const restaurant: Restaurant = {
  id: ${literal(data.restaurant.id)},
  name: ${literal(data.restaurant.name)},
  defaultLanguage: ${literal(data.restaurant.default_language)},
  supportedLanguages: ${literal(data.restaurant.supported_languages)},
  currency: ${literal(data.restaurant.currency)},
};

const restaurantId = restaurant.id;

export const categories: Category[] = [
${categoryLines.join("\n")}
];

export const menuItems: MenuItem[] = [
${itemLines.join("\n")}
];
`;

const target = resolve(process.cwd(), "src/lib/seed-data.ts");
writeFileSync(target, file, "utf8");
console.log(
  `Wrote ${target}: ${categories.length} categories, ${items.length} items, ` +
    `${items.filter((item) => item.price_minor !== null).length} priced, ` +
    `${items.filter((item) => item.photo_url).length} with photos.`,
);
